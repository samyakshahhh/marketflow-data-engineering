-- Company profile is slowly changing reference data: keep the latest payload
-- per symbol. Secondary pipeline - the price pipeline does not depend on it.
MERGE INTO SILVER.COMPANY_PROFILE t
USING (
    SELECT
        SYMBOL, COMPANY_NAME, INDUSTRY, SECTOR, EXCHANGE, CURRENCY, COUNTRY,
        MARKET_CAP, SOURCE_SYSTEM, BATCH_ID, RUN_ID, INGESTED_AT
    FROM SILVER.VW_COMPANY_PROFILE_STAGING
    WHERE INGESTED_AT >  TO_TIMESTAMP_NTZ(%(from_ts)s)
      AND INGESTED_AT <= TO_TIMESTAMP_NTZ(%(to_ts)s)
      AND SYMBOL IS NOT NULL
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY SYMBOL
        ORDER BY INGESTED_AT DESC, RAW_ID DESC
    ) = 1
) s
   ON t.SYMBOL = s.SYMBOL
WHEN MATCHED THEN UPDATE SET
    t.COMPANY_NAME  = s.COMPANY_NAME,
    t.INDUSTRY      = s.INDUSTRY,
    t.SECTOR        = s.SECTOR,
    t.EXCHANGE      = s.EXCHANGE,
    t.CURRENCY      = s.CURRENCY,
    t.COUNTRY       = s.COUNTRY,
    t.MARKET_CAP    = s.MARKET_CAP,
    t.SOURCE_SYSTEM = s.SOURCE_SYSTEM,
    t.BATCH_ID      = s.BATCH_ID,
    t.RUN_ID        = s.RUN_ID,
    t.INGESTED_AT   = s.INGESTED_AT,
    t.LOADED_AT     = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (
    SYMBOL, COMPANY_NAME, INDUSTRY, SECTOR, EXCHANGE, CURRENCY, COUNTRY,
    MARKET_CAP, SOURCE_SYSTEM, BATCH_ID, RUN_ID, INGESTED_AT, LOADED_AT
) VALUES (
    s.SYMBOL, s.COMPANY_NAME, s.INDUSTRY, s.SECTOR, s.EXCHANGE, s.CURRENCY, s.COUNTRY,
    s.MARKET_CAP, s.SOURCE_SYSTEM, s.BATCH_ID, s.RUN_ID, s.INGESTED_AT, CURRENT_TIMESTAMP()
);
